"""Write review_priority_v2.txt: which questions need a manual check, in what order.

    python make_review_priority.py

Reads questions.jsonl and (read-only) review_sheet.csv to show decisions already made.
Never writes review_sheet.csv.

Rule (fixed, no hand-picking): within each group, questions are ordered by
SHA-256("42:" + id), the same order build_questions.py uses.
  MUST     all no_reason (10) and all removed (5)
  SAMPLE   first N_SAMPLE test answerable questions in that order
  IF TIME  remaining test answerable questions, same order
  OPTIONAL dev answerable questions (prompt development only)
"""
import csv
import hashlib

from common import read_jsonl

N_SAMPLE = 15


def h(i):
    return hashlib.sha256(f"42:{i}".encode()).hexdigest()


def main():
    qs = read_jsonl("questions.jsonl")
    with open("review_sheet.csv", encoding="utf-8-sig") as f:
        sheet = list(csv.DictReader(f))
    dcol = next(k for k in sheet[0] if k.startswith("decision"))
    done = {r["id"]: r[dcol].strip() for r in sheet if r[dcol].strip()}

    nr = sorted((q for q in qs if q["type"] == "no_reason"), key=lambda q: h(q["id"]))
    rm = sorted((q for q in qs if q["type"] == "removed"), key=lambda q: h(q["id"]))
    ta = sorted((q for q in qs if q["type"] == "answerable" and q["split"] == "test"),
                key=lambda q: h(q["id"]))
    da = sorted((q for q in qs if q["type"] == "answerable" and q["split"] == "dev"),
                key=lambda q: h(q["id"]))
    groups = [
        ("MUST", "No-reason questions (all 10)", nr,
         "Read the WHOLE PR (description, commits, comments, diff incl. code comments and release "
         "notes). Keep only if the reason asked about is stated nowhere. These are the ground "
         "truth for abstention; one wrong label flips a headline number."),
        ("MUST", "Removed questions (all 5)", rm,
         "Check the question/answer as usual, AND read the 5 retrieved chunks for this id in "
         "results/retrieved_top5.jsonl: the answer must not be stated there (paraphrases count). "
         "The code already checked that the verbatim quote is absent and excluded PRs are not "
         "retrieved."),
        ("SAMPLE", f"Test answerable, first {N_SAMPLE} in hash order", ta[:N_SAMPLE],
         "Is the question unambiguous? Does the quote actually answer it? Is the gold answer "
         "right and not over-claiming? Is the question leading or copying the PR?"),
        ("IF TIME", f"Test answerable, remaining {len(ta) - N_SAMPLE}", ta[N_SAMPLE:],
         "Same checks. Doing all 50 lets the report say 'all test questions verified'."),
        ("OPTIONAL", "Dev answerable (prompt development only)", da,
         "Not used for results. Check only if you have spare time."),
    ]

    out = ["REVIEW PRIORITY v2  (generated by make_review_priority.py; review_sheet.csv untouched)",
           "",
           "Selection rule: fixed, not hand-picked. Within each group, ids are ordered by",
           "SHA-256('42:' + id), the same order build_questions.py uses. Describe it in the report",
           "as 'a pseudo-random sample chosen by a fixed rule (SHA-256 of question id, seed 42)'.",
           "The no-reason and removed sets are complete sets, not samples; the no-reason PRs were",
           "selected by Claude by reading them, so they are not random.",
           "",
           "How to mark: put keep / fix / drop in the 'decision' column of review_sheet.csv for",
           "the id. 'removed' rows (rm...) re-use the question of the matching q... row.",
           "",
           f"Already decided in review_sheet.csv: {len(done)} "
           + (f"({', '.join(f'{k}={v}' for k, v in sorted(done.items()))})" if done else ""),
           "",
           "Totals: MUST 15, SAMPLE 15, IF TIME 35, OPTIONAL 10  (75 rows)",
           "Minimum for the report = MUST + SAMPLE = 30 rows.",
           ""]
    n = 0
    for tag, title, rows, how in groups:
        out += ["=" * 90, f"[{tag}] {title}  ({len(rows)} rows)", f"What to check: {how}", ""]
        for q in rows:
            n += 1
            d = done.get(q["id"], "")
            mark = f"  [DONE: {d}]" if d else ""
            extra = ""
            if q["type"] == "removed":
                extra = f"\n        excluded PRs: {q['exclude_prs']}"
            if q.get("note"):
                extra += f"\n        note: {q['note']}"
            out.append(f"{n:>3}. {q['id']:<9} {q['split']:<5} PR #{q['pr_number']:<6}"
                       f" https://github.com/django/django/pull/{q['pr_number']}{mark}"
                       f"\n        Q: {q['question']}{extra}")
        out.append("")
    with open("review_priority_v2.txt", "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"{n} rows -> review_priority_v2.txt; already decided: {len(done)}")
    write_csv(groups, sheet, dcol)


NO_REASON_RETRIEVAL_CHECK = (
    " ALSO (test rows): open the other PRs listed in retrieved_prs; under retrieved context the "
    "question is only unanswerable if none of them states the reason either.")


def write_csv(groups, sheet, dcol, path="review_priority_v2.csv"):
    """Same groups/order as the txt, as a marking sheet. Decisions and notes already made in
    review_sheet.csv (v1) are COPIED in (v1 itself is never modified)."""
    v1 = {r["id"]: r for r in sheet}
    ret = {r["id"]: r for r in read_jsonl("results/retrieved_top5.jsonl")}
    cols = ["order", "tier", "id", "split", "type", "pr_number", "pr_url", "question",
            "gold_answer", "quote", "source_part", "exclude_prs", "retrieved_prs",
            "retrieved_chunk_ids", "claude_note", "what_to_check", "decision (keep/fix/drop)",
            "reviewer_notes", "copied_from_v1"]
    rows, n = [], 0
    for tag, _, qs, how in groups:
        for q in qs:
            n += 1
            old = v1.get(q["id"], {})
            dec, notes = old.get(dcol, "").strip(), old.get("reviewer_notes", "").strip()
            if notes == q.get("note", ""):
                notes = ""                     # v1 pre-filled the note column with Claude's note
            check = how + (NO_REASON_RETRIEVAL_CHECK
                           if q["type"] == "no_reason" and q["split"] == "test" else "")
            r = ret.get(q["id"], {})
            rows.append({"order": n, "tier": tag, "id": q["id"], "split": q["split"],
                         "type": q["type"], "pr_number": q["pr_number"],
                         "pr_url": f"https://github.com/django/django/pull/{q['pr_number']}",
                         "question": q["question"],
                         "gold_answer": q.get("gold_answer_if_present") or q["answer"],
                         "quote": q["quote"] or "", "source_part": q["source_part"] or "",
                         "exclude_prs": " ".join(map(str, q["exclude_prs"])),
                         "retrieved_prs": " ".join(map(str, r.get("retrieved_prs", []))),
                         "retrieved_chunk_ids": " ".join(r.get("chunk_ids", [])),
                         "claude_note": q.get("note", ""), "what_to_check": check,
                         "decision (keep/fix/drop)": dec, "reviewer_notes": notes,
                         "copied_from_v1": "yes" if (dec or notes) else ""})
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    print(f"{len(rows)} rows -> {path}; decisions copied from v1: "
          f"{sum(bool(r['decision (keep/fix/drop)']) for r in rows)}")


if __name__ == "__main__":
    main()
